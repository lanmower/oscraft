import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pack = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(pack, f), "utf8");
const rows = read("character-mapping.tsv").trim().split("\n").slice(1).map((line) => line.split("\t"));
const active = new Map();
for (const [, legacy, id, slot] of rows) if (!active.has(id)) active.set(id, { legacy, slot });
const label = (id) => id.split("_").map((word) => word[0].toUpperCase() + word.slice(1)).join(" ");
const output = `# Generated by scenarios/bota/tools/build-bota-pack.mjs. Do not edit by hand.\nreturn {\n${[...active.keys()].map((id) => `  ["${id}"] = "${label(id)}",`).join("\n")}\n}\n`;
const target = path.join(pack, "hero_acronyms.lua");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) {
    console.error("BOTA hero_acronyms.lua is stale: run node scenarios/bota/tools/build-bota-pack.mjs --apply");
    process.exit(1);
  }
  console.log(`BOTA hero_acronyms.lua current (${active.size} fullname hero IDs, no acronym-only active IDs)`);
} else {
  fs.writeFileSync(target, output);
  console.log(`BOTA hero_acronyms.lua generated (${active.size} fullname hero IDs)`);
}
