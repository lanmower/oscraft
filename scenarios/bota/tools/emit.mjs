import fs from "node:fs";
import path from "node:path";

const KEEP = /^\s*(#!|(#|--)\s*(SPDX-|Copyright|License)|(#|--)\s*Generated by .*Do not edit)/i;
const markerOf = (name) => (name.endsWith(".lua") ? "--" : "#");

export function stripComments(text, name) {
  const marker = markerOf(name);
  const code = [];
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (t.startsWith(marker) && !KEEP.test(t)) continue;
    code.push(line);
  }
  const collapsed = [];
  for (const l of code) {
    if (l.trim() === "" && (collapsed.length === 0 || collapsed.at(-1).trim() === "")) continue;
    collapsed.push(l);
  }
  while (collapsed.length && collapsed.at(-1).trim() === "") collapsed.pop();
  return collapsed.join("\n") + "\n";
}

export function emitCode(dir, name, code, check) {
  const file = path.join(dir, name);
  if (check) return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== code ? [name] : [];
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, code);
  return [];
}

export function emitSplit(dir, name, text, check) {
  return emitCode(dir, name, stripComments(text, name), check);
}

export function loadIds(dir) {
  const rows = fs.readFileSync(path.join(dir, "ability-688g-ids.tsv"), "utf8").split("\n").slice(1).filter(Boolean).map((line) => {
    const [source, anchor, code, alias] = line.split("\t");
    return [source + "\t" + anchor, { code, alias }];
  });
  return new Map(rows);
}
