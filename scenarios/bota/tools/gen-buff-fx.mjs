import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = ["abilities.osd", "abilities_ruleset.osd", "items.osd"];
const OUT = path.join(root, "buff_fx.lua");
const TICKS_PER_SECOND = 16;

const STATUS_NAMES = [
  "stun", "slow", "silence", "root", "invisibility", "taunt", "hex", "disarm", "spell_immunity", "invulnerable",
  "break", "mute", "physical_immunity", "death_prevention", "blind", "revealed",
];
const STATUS_EFFECTS = ["stun", "slow", "silence", "root", "invisibility"];

const KINDS = {
  stun: { school: "lightning", r: 0.9, motes: 6 },
  slow: { school: "frost", r: 1.0, motes: 5 },
  silence: { school: "arcane", r: 0.9, motes: 4 },
  root: { school: "nature", r: 1.1, motes: 7 },
  invisibility: { school: "shadow", r: 0.9, motes: 4 },
  taunt: { school: "blood", r: 1.0, motes: 5 },
  hex: { school: "arcane", r: 1.0, motes: 7 },
  disarm: { school: "physical", r: 0.9, motes: 4 },
  spell_immunity: { school: "holy", r: 1.2, motes: 8 },
  invulnerable: { school: "holy", r: 1.3, motes: 10 },
  break: { school: "poison", r: 0.9, motes: 4 },
  mute: { school: "shadow", r: 0.9, motes: 4 },
  physical_immunity: { school: "earth", r: 1.2, motes: 8 },
  death_prevention: { school: "holy", r: 1.1, motes: 6 },
  dot: { school: "poison", r: 0.9, motes: 5 },
  stat_up: { school: "wind", r: 1.0, motes: 6 },
  stat_down: { school: "blood", r: 0.9, motes: 4 },
  behaviour_1: { school: "nature", r: 1.0, motes: 6 },
};

const abilityLine = /^ability\("([^"]+)",.*$/;
const effectCall = /effect\("(\w+)"((?:,\s*\w+=-?\d+)*)\)/g;

function params(text) {
  const out = {};
  for (const m of text.matchAll(/(p\d)=(-?\d+)/g)) out[m[1]] = Number(m[2]);
  return out;
}

function auraOf(kind, p) {
  if (kind === "buff") return { kind: `behaviour_${p.p0}`, ticks: p.p1 };
  if (kind === "status") return STATUS_NAMES[p.p0] === "revealed" ? null : { kind: STATUS_NAMES[p.p0], ticks: p.p1 };
  if (STATUS_EFFECTS.includes(kind)) return { kind, ticks: p.p0 };
  if (kind === "dot") return { kind: "dot", ticks: p.p2 };
  if (kind === "timed_stat") return { kind: p.p1 > 0 ? "stat_up" : "stat_down", ticks: p.p2 };
  return null;
}

function collect() {
  const abilities = {};
  const kindsSeen = new Set();
  for (const file of SOURCES) {
    for (const line of fs.readFileSync(path.join(root, file), "utf8").split("\n")) {
      const head = abilityLine.exec(line);
      if (!head) continue;
      let best = null;
      for (const m of line.matchAll(effectCall)) {
        const aura = auraOf(m[1], params(m[2]));
        if (!aura || !aura.kind || !(aura.ticks > 0)) continue;
        if (!best || aura.ticks > best.ticks) best = aura;
      }
      if (best) {
        abilities[head[1]] = best;
        kindsSeen.add(best.kind);
      }
    }
  }
  return { abilities, kindsSeen };
}

function render({ abilities }) {
  const kindRows = Object.keys(KINDS)
    .map((k) => `    ["${k}"] = { school = "${KINDS[k].school}", r = ${KINDS[k].r}, motes = ${KINDS[k].motes} },`)
    .join("\n");
  const abilityRows = Object.keys(abilities)
    .sort()
    .map((n) => `    ["${n}"] = { kind = "${abilities[n].kind}", ticks = ${abilities[n].ticks} },`)
    .join("\n");
  return `-- Generated by scenarios/moba/tools/gen-buff-fx.mjs from abilities.osd, abilities_ruleset.osd and items.osd. Do not edit by hand.
local TICKS_PER_SECOND = ${TICKS_PER_SECOND}

local buff_fx = {
  kinds = {
${kindRows}
  },
  abilities = {
${abilityRows}
  },
}

function buff_fx.aura_for(ability_name)
  local held = buff_fx.abilities[ability_name]
  if held == nil then return nil end
  local look = buff_fx.kinds[held.kind]
  return held.kind, look.school, math.floor(held.ticks * 1000 / TICKS_PER_SECOND)
end

return buff_fx
`;
}

const collected = collect();
for (const kind of collected.kindsSeen) {
  if (!KINDS[kind]) throw new Error(`no look for buff kind ${kind}`);
}
const text = render(collected);

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("buff_fx.lua is stale: run node scenarios/moba/tools/gen-buff-fx.mjs");
    process.exit(1);
  }
  console.log(`buff_fx.lua current: ${Object.keys(collected.abilities).length} abilities`);
} else {
  fs.writeFileSync(OUT, text);
  const byKind = {};
  for (const a of Object.values(collected.abilities)) byKind[a.kind] = (byKind[a.kind] || 0) + 1;
  console.log(`wrote buff_fx.lua: ${Object.keys(collected.abilities).length} abilities`, JSON.stringify(byKind));
}
