import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const moba = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const MELEE_CUTOFF_UNITS = 128;
const UNITS_PER_CELL = 64;
const FIXED_ONE = 65536;
const HERO_LINE = /^unit\("hero", .*$/m;
const HERO_RANGE = /weapon_range_milli=\d+/;
const LUA_NAME = "melee_reach.lua";
const LUA_HEADER = "-- Generated by scenarios/moba/tools/gen-melee-reach.mjs. Do not edit by hand.";

const cutoffMilli = (MELEE_CUTOFF_UNITS * 1000) / UNITS_PER_CELL;
const cutoffQ16 = (MELEE_CUTOFF_UNITS * FIXED_ONE) / UNITS_PER_CELL;
if (!Number.isInteger(cutoffMilli) || !Number.isInteger(cutoffQ16)) {
  console.error("gen-melee-reach: the cutoff does not convert to whole milli cells and Q16");
  process.exit(1);
}

const unitsPath = path.join(moba, "units.osd");
const luaPath = path.join(moba, LUA_NAME);
const units = fs.readFileSync(unitsPath, "utf8");
if (!HERO_LINE.test(units)) {
  console.error('gen-melee-reach: units.osd has no unit("hero") line');
  process.exit(1);
}
const nextUnits = units.replace(HERO_LINE, (line) => line.replace(HERO_RANGE, "weapon_range_milli=" + cutoffMilli));
const nextLua = LUA_HEADER + "\nreturn {\n  cutoff_q16 = " + cutoffQ16 + ",\n}\n";
const current = (file) => (fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "");
const outputs = [
  { file: unitsPath, text: nextUnits },
  { file: luaPath, text: nextLua },
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(({ file, text }) => current(file) !== text).map(({ file }) => path.relative(moba, file));
  if (stale.length > 0) {
    console.error("gen-melee-reach: stale " + stale.join(", ") + "; run without --check");
    process.exit(1);
  }
  console.log("gen-melee-reach: ok (cutoff " + MELEE_CUTOFF_UNITS + " units = " + cutoffMilli + " milli cells = " + cutoffQ16 + " q16)");
} else {
  for (const { file, text } of outputs) if (current(file) !== text) fs.writeFileSync(file, text);
  console.log("gen-melee-reach: wrote cutoff " + MELEE_CUTOFF_UNITS + " units");
}
