import fs from "node:fs";
import path from "node:path";

export const provenanceFile = (mobaDir, source) => path.join(mobaDir, "provenance", `${source}.tsv`);

export function loadProvenance(mobaDir, source) {
  const file = provenanceFile(mobaDir, source);
  if (!fs.existsSync(file)) return [];
  return fs.readFileSync(file, "utf8").split("\n").slice(1).filter(Boolean).map((line) => {
    const [anchor, kind, ...note] = line.split("\t");
    return { anchor, kind, note: note.join("\t") };
  });
}

export function notesByAnchor(mobaDir, source) {
  const by = new Map();
  for (const row of loadProvenance(mobaDir, source)) {
    if (!by.has(row.anchor)) by.set(row.anchor, []);
    by.get(row.anchor).push(row.note);
  }
  return by;
}


export const SIDECAR_HEADER = "anchor\tkind\tnote";
const KEEP = /^\s*(#!|(#|--)\s*(SPDX-|Copyright|License)|(#|--)\s*Generated by .*Do not edit)/i;

const markerOf = (name) => (name.endsWith(".lua") ? "--" : "#");
const isTsv = (name) => name.endsWith(".tsv");


export function classify(note) {
  if (/UNVERIFIED/.test(note)) return "unverified";
  if (/\bMissing\b/.test(note)) return "missing";
  if (/^(Source|SOURCE|Generated by)\b/.test(note)) return "source";
  if (/war3map\.j|ability\.ini|\.slk|\.ini[: ]|SteamDatabase|items\.txt|npc_abilities|\bL\d+\b/.test(note)) return "provenance";
  return "rationale";
}

function anchorOf(line, name, state) {
  if (isTsv(name)) {
    if (!state.header) { state.header = true; return "header"; }
    return line.split("\t")[0].trim() || "file";
  }
  if (name.endsWith(".lua")) {
    const m = line.match(/^\s*(?:local\s+)?\[?"?([\w.]+)"?\]?\s*[=(]/) ?? line.match(/^\s*(\w+)/);
    return m ? m[1] : "file";
  }
  const m = line.match(/^\s*(\w+)\(\s*(?:"([^"]*)"|([^,)\s=]+))/) ?? line.match(/^\s*([A-Za-z0-9_.-]+)/) ?? line.match(/^\s*(\S+)/);
  return m ? (m[2] ?? m[3] ?? m[1]) : "file";
}

export function splitComments(text, name) {
  const marker = markerOf(name);
  const lines = text.split("\n");
  const rows = [];
  const code = [];
  const pending = [];
  const state = { header: false, seenCode: false };
  let blankAfterPending = false;
  const flush = (anchor) => {
    for (const note of pending) rows.push([anchor, classify(note), note]);
    pending.length = 0;
    blankAfterPending = false;
  };
  for (const line of lines) {
    const t = line.trim();
    if (t.startsWith(marker) && KEEP.test(t)) {
      code.push(line);
      continue;
    }
    if (t.startsWith(marker)) {
      const note = t.slice(marker.length).replace(/^ /, "").replace(/[\t\r\n]+/g, " ").trimEnd();
      if (note !== "") pending.push(note);
      continue;
    }
    if (t === "") {
      if (pending.length) blankAfterPending = true;
      code.push(line);
      continue;
    }
    const anchor = anchorOf(line, name, state);
    if (pending.length) flush(!state.seenCode ? "file" : anchor);
    state.seenCode = true;
    code.push(line);
  }
  if (pending.length) flush("file");
  const collapsed = [];
  for (const l of code) {
    if (l.trim() === "" && (collapsed.length === 0 || collapsed.at(-1).trim() === "")) continue;
    collapsed.push(l);
  }
  while (collapsed.length && collapsed.at(-1).trim() === "") collapsed.pop();
  return { code: collapsed.join("\n") + "\n", rows };
}

export function rowsToTsv(rows) {
  return [SIDECAR_HEADER, ...rows.map((r) => r.join("\t"))].join("\n") + "\n";
}

export function emitParts(dir, name, code, rows, check) {
  const targets = [[path.join(dir, name), code], [provenanceFile(dir, name), rowsToTsv(rows)]];
  const stale = targets.filter(([f, want]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== want).map(([f]) => path.relative(dir, f));
  if (check) return stale;
  for (const [f, want] of targets) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, want);
  }
  return [];
}

export function emitSplit(dir, name, text, check) {
  const { code, rows } = splitComments(text, name);
  return emitParts(dir, name, code, rows, check);
}
