import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitSplit, loadIds } from "./emit.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const moba = path.join(here, "..");
const lni = process.argv.slice(2).find((a) => !a.startsWith("--"));
const check = process.argv.includes("--check");
if (!lni) { console.error("usage: gen-ability-keys.mjs <g688-lni dir> [--check]"); process.exit(2); }

const keyOf = new Map();
let id = null;
for (const line of fs.readFileSync(path.join(lni, "ability.ini"), "utf8").split("\n")) {
  const sec = /^\[(.*)\]\s*$/.exec(line);
  if (sec) { id = sec[1]; continue; }
  const hot = /^Hotkey\s*=\s*"(.)"/.exec(line);
  if (hot && id) keyOf.set(id, hot[1].toLowerCase());
}

const out = new Map();
const ids = loadIds(moba);
const files = fs.readdirSync(moba).filter((f) => /^abilities_688g_b\d+\.osd$/.test(f)).sort();
for (const f of files) {
  for (const line of fs.readFileSync(path.join(moba, f), "utf8").split("\n")) {
    const a = /^ability\("([a-z0-9_]+)"/.exec(line);
    if (!a) continue;
    const alias = ids.get(`${f}\t${a[1]}`)?.alias;
    if (alias && keyOf.has(alias)) out.set(a[1], keyOf.get(alias));
  }
}
const rows = [...out].sort((x, y) => (x[0] < y[0] ? -1 : 1));
const text = [
  "-- Generated by tools/gen-ability-keys.mjs from the 6.88g ability.ini Hotkey field. Do not edit by hand.",
  "return {",
  ...rows.map(([n, k]) => `  ${n} = "${k}",`),
  "}",
  "",
].join("\n");
const stale = emitSplit(moba, "ability_keys.lua", text, check);
if (stale.length) { console.error(`${stale.join(", ")} differ from the ability.ini Hotkey field; run gen-ability-keys.mjs <lni dir>`); process.exit(1); }
console.log(`ability_keys.lua: ${rows.length} keys`);
