import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitSplit } from "./provenance.mjs";

const moba = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const table = (f) => {
  const [head, ...rows] = fs.readFileSync(path.join(moba, f), "utf8").trim().split("\n").map((l) => l.split("\t"));
  return rows.map((r) => Object.fromEntries(head.map((k, i) => [k, r[i] ?? ""])));
};
const TAG = { depot: 1, side_depot: 2, secret_depot: 4 };
const idOfCode = new Map(table("items_688g.tsv").filter((r) => r.code688g && r.status !== "not_in_688g" && r.method !== "added_state").map((r) => [r.code688g, r.form_of || r.id]));
const osd = fs.readFileSync(path.join(moba, "items.osd"), "utf8");
const declared = new Set([...osd.matchAll(/^item\("([^"]+)"/gm)].map((m) => m[1]));

let dropped = 0;
const shops = table("shops_688g.tsv").map((r) => {
  const items = [];
  for (const code of r.items_688g.split(",").filter(Boolean)) {
    const id = idOfCode.get(code);
    if (id && declared.has(id)) { if (!items.includes(id)) items.push(id); } else dropped++;
  }
  return { ...r, items: items.sort() };
});

const extra = table("shops_extra_688g.tsv");
const SOURCES = new Set(["6.88g", "web", "GUESS"]);
const nativeIds = new Set(shops.flatMap((s) => s.items));
const problems = [];
for (const r of extra) {
  if (!declared.has(r.item)) problems.push(`${r.item}: in shops_extra_688g.tsv but not an items.osd item`);
  if (nativeIds.has(r.item)) problems.push(`${r.item}: in shops_extra_688g.tsv but a 6.88g shop of shops_688g.tsv lists it`);
  if (!SOURCES.has(r.source) || r.basis === "") problems.push(`${r.item}: needs a source of 6.88g, web or GUESS and its basis`);
  const codes = r.shops.split(",").filter(Boolean);
  const hit = shops.filter((s) => codes.includes(s.shop_code));
  if (hit.length === 0 || codes.some((c) => !shops.some((s) => s.shop_code === c))) problems.push(`${r.item}: shops ${r.shops} are not all shops of shops_688g.tsv`);
  for (const s of hit) if (!s.items.includes(r.item)) s.items.push(r.item);
}
for (const s of shops) s.items.sort();
const listedIds = new Set(shops.flatMap((s) => s.items));
for (const m of osd.matchAll(/^item\("([^"]+)"[^\n]*$/gm)) {
  if (!/no_buy=true/.test(m[0]) && /tags=\[[^\]]*"/.test(m[0]) && !listedIds.has(m[1])) problems.push(`${m[1]}: tagged buyable item that no shop sells`);
}
if (problems.length > 0) { console.error(problems.join("\n")); process.exit(1); }

const lines = shops.map((s) => `  { id = ${s.prop_id}, code = "${s.shop_code}", name = ${JSON.stringify(s.shop_name)}, tag = ${TAG[s.prop_kind]}, x = ${s.x_milli}, y = ${s.y_milli},\n    items = { ${s.items.map((i) => `"${i}"`).join(", ")} } },`);
const text = `-- Generated by scenarios/moba/tools/gen-shops-688g.mjs from shops_688g.tsv. Do not edit by hand.\n-- One entry per shop prop: x and y in milli, tag the depot tag bit it stocks under (items.osd item_tags order), items the oscraft item ids it sells.\nreturn {\n  shops = {\n${lines.join("\n")}\n  },\n}\n`;
const stale = emitSplit(moba, "shops_688g.lua", text, process.argv.includes("--check"));
if (stale.length) { console.error(`${stale.join(", ")} stale: run gen-shops-688g.mjs`); process.exit(1); }
console.log(`shops ${shops.length}; items listed ${listedIds.size}; items from shops_extra_688g.tsv ${extra.length}; 6.88g codes without an oscraft item ${dropped}`);
