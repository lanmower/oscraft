import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const moba = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(moba, file), "utf8");
const SIDE_TAGS = new Set(["sentinel", "scourge"]);
const GENERATED_HEADER = "-- Generated by scenarios/moba/tools/gen-hero-sides.mjs from hero_sides.tsv. Do not edit by hand.";

const roster = new Set();
for (const file of ["units.osd", "units_heroes.osd"]) {
  const text = read(file);
  const controlled = new Set([...text.matchAll(/^unit_extra\("(\w+)",[^\n]*player_controlled=True/gm)].map((m) => m[1]));
  for (const m of text.matchAll(/^unit\("(\w+)",[^\n]*/gm)) {
    const model = /model="([^"]*)"/.exec(m[0]);
    if (controlled.has(m[1]) && model && model[1] !== "") roster.add(m[1]);
  }
}

const rows = read("hero_sides.tsv")
  .split("\n")
  .slice(1)
  .filter((line) => line.trim() !== "")
  .map((line) => {
    const [id, side = ""] = line.split("\t");
    return { id, side };
  });

const problems = [];
const listed = new Set();
for (const { id, side } of rows) {
  if (listed.has(id)) problems.push(`${id} is listed twice`);
  listed.add(id);
  if (!roster.has(id)) problems.push(`${id} is not a hero in units.osd or units_heroes.osd`);
  if (side !== "" && !SIDE_TAGS.has(side)) problems.push(`${id} has side "${side}": use sentinel, scourge or leave it blank`);
}
for (const id of roster) if (!listed.has(id)) problems.push(`hero ${id} has no row in hero_sides.tsv`);
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const tagged = rows.filter((row) => row.side !== "");
const text = [GENERATED_HEADER, "return {", ...tagged.map((row) => `  ${row.id} = "${row.side}",`), "}", ""].join("\n");
const target = path.join(moba, "hero_sides.lua");

if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== text) {
    console.error("hero_sides.lua is stale: run node scenarios/moba/tools/gen-hero-sides.mjs");
    process.exit(1);
  }
  console.log(`hero_sides.lua is current: ${tagged.length} tagged of ${rows.length} heroes`);
} else {
  fs.writeFileSync(target, text);
  console.log(`hero_sides.lua written: ${tagged.length} tagged of ${rows.length} heroes`);
}
