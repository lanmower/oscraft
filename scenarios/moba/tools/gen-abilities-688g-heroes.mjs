#!/usr/bin/env node
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitSplit } from "./emit.mjs";
import {
  LABEL_EFFECTS,
  TARGET_BY_CODE,
  classify,
  definedAbilityNames,
  parseDataLabels,
  parseLevels,
  perlevelByUnit,
  provenHeroes,
  readRows,
  TICKS_PER_SECOND,
} from "./ability-688g.mjs";

const moba = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = "abilities_688g_heroes.osd";
const check = process.argv.includes("--check");

const proven = provenHeroes(moba);
const inventory = readRows(path.join(moba, "abilities-inventory.tsv"));
const present = definedAbilityNames(moba, OUT_FILE);
const perlevel = perlevelByUnit(moba);

const q = (s) => JSON.stringify(s);
const padTo = (values, n) => Array.from({ length: n }, (_, k) => values[Math.min(k, values.length - 1)] ?? 0);

function effectLines(name, labels, levels) {
  const effects = [];
  const scaled = [];
  for (const [label, spec] of Object.entries(LABEL_EFFECTS)) {
    const values = labels.get(label);
    if (!values || !values.some((v) => v > 0)) continue;
    const ranks = padTo(values.map((v) => Math.round(v * spec.scale)), levels);
    const index = effects.length;
    effects.push(`effect(${q(spec.kind)}, p0=${ranks[0]}, p1=0, p2=0, p3=0)`);
    if (ranks.some((v) => v !== ranks[0])) scaled.push(`ability_scaled(${q(name)}, ${index}, 0, [${ranks}])`);
  }
  return { effects, scaled };
}

function abilityBlock(hero, name, unit, code) {
  const row = perlevel.get(`${unit}\t${code}`);
  const cooldownSeconds = parseLevels(row[6]);
  const costs = parseLevels(row[7]);
  const labels = parseDataLabels(row[9]);
  const declaredLevels = Math.max(cooldownSeconds.length, costs.length, 1);
  const ultimate = declaredLevels === 3;
  const ranks = ultimate ? 3 : 4;
  const cooldown = padTo(cooldownSeconds.map((s) => Math.round(s * TICKS_PER_SECOND)), ranks);
  const energy = padTo(costs, ranks);
  const targetCode = labels.has("目标类型") ? labels.get("目标类型")[0] : 0;
  const target = TARGET_BY_CODE[targetCode] ?? "none";
  const { effects, scaled } = effectLines(name, labels, ranks);
  const gates = ultimate ? [6, 11, 16] : [1, 3, 5, 7];
  return [
    `ability(${q(name)}, ${cooldown[0]}, ${energy[0]}, ${q(target)}, [${effects.join(", ")}])`,
    `skill(${q(name)}, ultimate=${ultimate ? "True" : "False"}, gates=[${gates}], damage=[${Array(ranks).fill(0)}], cooldown=[${cooldown}], energy=[${energy}])`,
    ...scaled,
  ];
}

const lines = [];
const seen = new Set();
for (const [hero, slot, name, kind] of inventory) {
  if (kind !== "ability" || !proven.has(hero)) continue;
  if (seen.has(name)) continue;
  seen.add(name);
  const unit = proven.get(hero);
  const verdict = classify(hero, unit, name, present, perlevel);
  if (verdict.status !== "ROW") continue;
  lines.push(...abilityBlock(hero, name, unit, verdict.code));
}

const text = [
  "# Generated by scenarios/moba/tools/gen-abilities-688g-heroes.mjs from abilities-inventory.tsv, heroes_688g.tsv and abilities_688g_perlevel.tsv. Do not edit by hand.",
  ...lines,
  "",
].join("\n");

if (check) {
  const stale = emitSplit(moba, OUT_FILE, text, true);
  if (stale.length) {
    console.error(`gen-abilities-688g-heroes --check: ${stale.join(", ")} differs from the generator output; run node scenarios/moba/tools/gen-abilities-688g-heroes.mjs`);
    process.exit(1);
  }
  console.log(`gen-abilities-688g-heroes --check: ok (${lines.length} lines)`);
} else {
  emitSplit(moba, OUT_FILE, text, false);
  console.log(`wrote ${path.join(moba, OUT_FILE)}: ${lines.length} lines`);
}
