import fs from "node:fs";
import path from "node:path";
import { splitComments, loadProvenance, emitParts, emitSplit } from "./provenance.mjs";

const args = process.argv.slice(2);
const opt = (name, dflt) => (args.includes(name) ? args[args.indexOf(name) + 1] : dflt);
const outDir = opt("--out", "scenarios/moba");
const check = args.includes("--check");
const scriptPath = opt("--script", opt("--src", null) && path.join(opt("--src", null), "script.txt"));
if (!scriptPath) throw new Error("--src <dir> or --script <file> is required");

const GX = 35, GY = 35, UNIT_MILLI = 1000 / 64;
const toMilli = (wx, wy) => [Math.round((GX * 64 + wx + 8192) * UNIT_MILLI), Math.round((GY * 64 + 8192 - wy) * UNIT_MILLI)];
const SIZE_NAMES = ["small", "medium", "large", "ancient"];
const RING_UNITS = 42.5;
const num = (s) => (/^0x/i.test(s.trim()) ? parseInt(s, 16) : Number(s));
const sum = (expr) => [...expr.matchAll(/[-+]?\d+\.?\d*/g)].reduce((a, m) => a + Number(m[0]), 0);

const script = fs.readFileSync(scriptPath, "latin1");
const fnBody = (name) => {
  const m = script.match(new RegExp(`function ${name} takes[^\\n]*\\n([\\s\\S]*?)\\nendfunction`));
  if (!m) throw new Error(`function ${name} not found in ${scriptPath}`);
  return m[1];
};

const rects = {};
for (const m of script.matchAll(/set (\w+)=Rect\(([^)]*)\)/g)) rects[m[1]] = m[2].split(",").map(sum);

const camps = [...fnBody("KPE").matchAll(/call KKE\(g,(\w+),(\w+),(0x[0-9A-Fa-f]+|-?\d+),(0x[0-9A-Fa-f]+|-?\d+),(\d+)\)/g)]
  .map((m) => ({ check: rects[m[1]], spawn: rects[m[2]], id: num(m[3]), facing: num(m[4]), size: num(m[5]) }));
if (camps.length !== 15) throw new Error(`expected 15 KKE calls, found ${camps.length}`);
if (camps.some((c) => !c.check || !c.spawn)) throw new Error("a camp rect global was not found");

const byId = new Map();
for (const c of camps) if (!byId.has(c.id)) byId.set(c.id, c);

const options = {};
let size = null, option = null;
for (const raw of fnBody("KBE").split("\n")) {
  const line = raw.trim();
  let m;
  if ((m = line.match(/^(?:if|elseif) KDE==(\d+) then$/))) { size = Number(m[1]); continue; }
  if ((m = line.match(/^(?:if|elseif) i==(\d+) then$/))) { option = Number(m[1]); continue; }
  if ((m = line.match(/^call (\w+)\(x,y,a\)$/)) && size !== null && option !== null) (options[size] ??= {})[option] = m[1];
}
const members = (fn) => [...fnBody(fn).matchAll(/call JWE\('(\w{4})',x,y,a\)/g)].map((m) => m[1]);
for (const [k, want] of [[0, 6], [1, 5], [2, 5], [3, 5]]) {
  if (Object.keys(options[k] ?? {}).length !== want) throw new Error(`size ${k}: expected ${want} options`);
}

const tsv = fs.readFileSync(path.join(outDir, "creeps_688g.tsv"), "utf8").split("\n").filter((l) => l && !l.startsWith("#")).map((l) => l.split("\t"));
const kindOf = Object.fromEntries(tsv.slice(1).map((r) => [r[1], r[0]]));

const lines = [
  "# Neutral camps of the 6.88g map, generated by scenarios/moba/tools/gen-neutral-688g.mjs from the map script (camp pass KPE, rolls KBE).",
  "# 14 camps: 2 small, 4 medium, 6 large, 2 ancient. A camp spawns at 0:30 and on each whole minute while no unit stands in its check rect.",
  "# The script rolls the composition per spawn; each camp here holds one stand-in option, ((camp id - 1) mod options) + 1.",
];
for (const c of [...byId.values()].sort((a, b) => a.id - b.id)) {
  const n = Object.keys(options[c.size]).length;
  const pick = ((c.id - 1) % n) + 1;
  const raws = members(options[c.size][pick]);
  const [cx, cy] = [(c.spawn[0] + c.spawn[2]) / 2, (c.spawn[1] + c.spawn[3]) / 2];
  lines.push(`# camp ${c.id} ${SIZE_NAMES[c.size]} option ${pick} of ${n}; spawn centre ${cx},${cy}; check rect ${c.check.join(",")}; facing ${c.facing}`);
  raws.forEach((raw, k) => {
    const kind = kindOf[raw];
    if (!kind) throw new Error(`rawcode ${raw} has no row in creeps_688g.tsv`);
    const a = ((c.facing + (360 * k) / raws.length) * Math.PI) / 180;
    const [x, y] = toMilli(cx + RING_UNITS * Math.cos(a), cy + RING_UNITS * Math.sin(a));
    lines.push(`spawn("${kind}", -1, ${x}, ${y})`);
  });
}

const rectMilli = (r) => {
  const [ax, ay] = toMilli(r[0], r[1]);
  const [bx, by] = toMilli(r[2], r[3]);
  return [Math.min(ax, bx), Math.min(ay, by), Math.max(ax, bx), Math.max(ay, by)];
};
const luaLines = [
  "-- Generated by tools/gen-neutral-688g.mjs from the 6.88g map script (camp pass KPE, option roll KBE, composition functions). Do not edit by hand.",
  "-- One row per camp: id = the script's camp id (the key of its last-option memory uJ), size, check = the rect {x1, y1, x2, y2} that must hold no unit for a spawn",
  "-- (KKE 26817-26821), centre = the spawn rect centre {x, y}, facing = the degrees every member is created with (KKE argument a, KBE 26829-26843), options = the unit kinds each option creates (KBE 26738-26805). Milli coordinates.",
  "return {",
];
for (const c of [...byId.values()].sort((a, b) => a.id - b.id)) {
  const n = Object.keys(options[c.size]).length;
  const opts = [];
  for (let i = 1; i <= n; i++) opts.push(`{${members(options[c.size][i]).map((raw) => {
    if (!kindOf[raw]) throw new Error(`rawcode ${raw} has no row in creeps_688g.tsv`);
    return `"${kindOf[raw]}"`;
  }).join(", ")}}`);
  const [cx, cy] = toMilli((c.spawn[0] + c.spawn[2]) / 2, (c.spawn[1] + c.spawn[3]) / 2);
  luaLines.push(`  { id = ${c.id}, size = "${SIZE_NAMES[c.size]}", check = {${rectMilli(c.check).join(", ")}}, centre = {${cx}, ${cy}}, facing = ${c.facing},`);
  luaLines.push(`    options = {${opts.join(", ")}} },`);
}
luaLines.push("}", "");
const luaText = luaLines.join("\n");

const file = path.join(outDir, "neutral.osd");
const head = splitComments(lines.join("\n") + "\n", "neutral.osd");
const oldCode = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
const oldRows = loadProvenance(outDir, "neutral.osd").map((r) => [r.anchor, r.kind, r.note]);
const headKept = oldCode.startsWith(head.code);
const tail = headKept ? oldCode.slice(head.code.length) : "";
const rows = [...head.rows, ...oldRows.slice(head.rows.length)];
if (check) {
  if (!headKept || emitParts(outDir, "neutral.osd", head.code + tail, rows, true).length) { console.error("neutral.osd or its provenance is out of date with the script"); process.exit(1); }
  if (emitSplit(outDir, "camps_688g.lua", luaText, true).length) { console.error("camps_688g.lua or its provenance is out of date with the script"); process.exit(1); }
  console.error("neutral.osd and camps_688g.lua are up to date");
} else {
  if (!headKept) throw new Error("neutral.osd does not start with the generated camp block; the lines after it are kept, so reconcile by hand");
  emitParts(outDir, "neutral.osd", head.code + tail, rows, false);
  emitSplit(outDir, "camps_688g.lua", luaText, false);
console.error(`neutral.osd: ${byId.size} camps, ${lines.filter((l) => l.startsWith("spawn(")).length} members`);
}
