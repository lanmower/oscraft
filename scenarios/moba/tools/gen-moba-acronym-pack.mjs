#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const source = path.join(root, "scenarios", "moba");
const out = path.join(root, "scenarios", "moba-acronyms");
const check = process.argv.includes("--check");
const apply = process.argv.includes("--apply");
const fileExt = new Set([".lua", ".osd", ".json", ".txt", ".tsv", ".osdt", ".png", ".jpg", ".jpeg", ".webp", ".glb", ".gltf", ".bin", ".ogg", ".wav", ".ktx2"]);
const textExt = new Set([".lua", ".osd", ".json", ".txt", ".tsv"]);
const table = new Map([...fs.readFileSync(path.join(source, "hero_acronyms.lua"), "utf8").matchAll(/^\s*\["([^"]+)"\] = "([^"]*)",/gm)].map((m) => [m[1], m[2].toLowerCase()]));
const units = fs.readFileSync(path.join(source, "units_heroes.osd"), "utf8");
const ids = [...units.matchAll(/^unit\("(\w+)"/gm)].map((m) => m[1]);
const display = new Map([...fs.readFileSync(path.join(source, "panels.lua"), "utf8").matchAll(/^\s+(\w+) = \{ "([^"]+)",/gm)].map((m) => [m[1], m[2]]));
const mapping = new Map();
for (const id of ids) {
  const name = display.get(id) ?? id;
  const acro = table.get(name);
  if (!acro || !/^[a-z]{1,3}$/.test(acro)) throw new Error(`missing acronym for ${id} (${name})`);
  if (mapping.has(acro)) throw new Error(`acronym collision at ${acro}: ${mapping.get(acro)} and ${id}`);
  mapping.set(acro, id);
}
if (mapping.size !== table.size) throw new Error(`roster mapping ${mapping.size} does not match acronym table ${table.size}`);
const byLength = [...mapping.entries()].sort((a, b) => b[1].length - a[1].length || a[1].localeCompare(b[1]));
const pattern = new RegExp(`(?<![A-Za-z0-9_-])(?:${byLength.map(([, id]) => id).join("|")})(?![A-Za-z0-9_-])`, "g");
const rename = (text) => text.replace(pattern, (id) => [...mapping].find(([acro, source]) => source === id)[0]);
const inverse = new Map([...mapping].map(([acro, id]) => [id, acro]));
const rewrite = (text) => text.replace(new RegExp(`(?<![A-Za-z0-9_-])(?:${[...inverse.keys()].sort((a, b) => b.length - a.length).join("|")})(?![A-Za-z0-9_-])`, "g"), (id) => inverse.get(id));
const files = new Map();
const walk = (dir, rel = "") => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name), next = path.posix.join(rel, entry.name);
    if (entry.isDirectory()) { if (entry.name !== "tools") walk(abs, next); }
    else if (fileExt.has(path.extname(entry.name))) files.set(next, abs);
  }
};
walk(source);
const outputs = new Map();
const copies = new Map();
for (const [rel, abs] of files) {
  let targetRel = rel;
  if (rel.startsWith("assets/models/")) {
    const base = path.basename(rel, ".glb");
    if (inverse.has(base)) targetRel = `assets/models/${inverse.get(base)}-skinned.glb`;
  }
  if (rel.startsWith("assets/icons/heroes/")) {
    const base = path.basename(rel).replace(/-skinned\.(png|jpg|jpeg|webp)$/, "");
    if (inverse.has(base)) targetRel = path.posix.join(path.dirname(rel), `${inverse.get(base)}${path.extname(rel)}`);
  }
  if (textExt.has(path.extname(rel))) {
    let text = fs.readFileSync(abs, "utf8");
    if (rel === "hero_acronyms.lua") text = `-- Generated by scenarios/moba/tools/gen-moba-acronym-pack.mjs. Do not edit by hand.\nreturn {\n${[...mapping.keys()].map((acro) => `  ["${acro}"] = "${acro.toUpperCase()}",`).join("\n")}\n}\n`;
    else if (rel === "manifest.json") text = fs.readFileSync(abs, "utf8");
    else text = rewrite(text);
    if (rel === "manifest.json") {
      const manifest = JSON.parse(text);
      manifest.name = "moba-acronyms";
      manifest.ui = "moba_ui.json";
      manifest.effects = "moba_ui.json";
      text = JSON.stringify(manifest, null, 2) + "\n";
    }
    if (rel === "moba_ui.json") {
      const ui = JSON.parse(text);
      const old = ui.heroAcronyms ?? {};
      ui.heroAcronyms = Object.fromEntries([...mapping.keys()].map((acro) => [acro, acro.toUpperCase()]));
      ui.identifierMode = "default-dota-acronyms";
      ui.heroProvenance = Object.fromEntries([...mapping].map(([acro, id]) => [acro, display.get(id) ?? id]));
      ui.legacyHeroAcronyms = old;
      text = JSON.stringify(ui, null, 2) + "\n";
    }
    outputs.set(path.join(out, targetRel), text);
  } else copies.set(path.join(out, targetRel), abs);
}
const acronymRows = [...mapping].map(([acro, id]) => [id, display.get(id) ?? id, acro, acro.toUpperCase()].join("\t"));
outputs.set(path.join(out, "IDENTIFIERS.md"), `# Default Dota/MOBA identifiers: acronyms only

Active hero identifiers are the lowercase forms of \`scenarios/moba/hero_acronyms.lua\` values. Full Dota names and source slugs are historical provenance only.

The default URL resolves to \`scenarios/moba-acronyms\` because \`js/client/pack_load.js\` sets \`PACK_PARAM\` to that path when no \`pack\` or \`package\` query parameter is present. \`?package=scenarios/moba\` remains the non-active historical source pack. \`?package=scenarios/bota\` remains the opt-in BOTA pack.

Collision rule: \`gen-hero-acronyms.mjs\` applies \`moba_ui.json\` overrides first, then its deterministic initialism rule, then the first unused three-letter alternative from the name's flattened letters. This generated pack refuses duplicate active IDs.

## Mapping

| Source Dota ID | Historical display name | Active acronym ID |
| --- | --- | --- |
${[...mapping].map(([acro, id]) => `| \`${id}\` | ${display.get(id) ?? id} | \`${acro}\` |`).join("\n")}
`);
outputs.set(path.join(out, "identifier-map.tsv"), ["source_id\thistorical_name\tactive_id\tactive_label", ...acronymRows].join("\n") + "\n");
if (check) {
  const expected = [...outputs.keys(), ...copies.keys()];
  const drift = expected.filter((abs) => !fs.existsSync(abs) || (outputs.has(abs) && fs.readFileSync(abs, "utf8") !== outputs.get(abs)));
  if (drift.length) { console.error(`moba acronym pack drift: ${drift.length} files\n${drift.slice(0, 20).map((p) => path.relative(out, p)).join("\n")}`); process.exit(1); }
  console.log(`moba acronym pack check ok: ${mapping.size} acronym-only heroes, ${outputs.size} generated files, ${copies.size} assets`);
} else if (apply) {
  for (const [abs, text] of outputs) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, text); }
  for (const [abs, src] of copies) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.copyFileSync(src, abs); }
  console.log(`moba acronym pack generated: ${mapping.size} acronym-only heroes, ${outputs.size} generated files, ${copies.size} assets`);
} else {
  console.log(`moba acronym pack plan: ${mapping.size} acronym-only heroes, ${outputs.size} generated files, ${copies.size} assets`);
  console.log(`acronyms: ${[...mapping.keys()].join(",")}`);
}
