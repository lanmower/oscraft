import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const moba = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(moba, f), "utf8");

const kinds = [];
for (const file of ["units.osd", "units_heroes.osd"]) {
  const text = read(file);
  const controlled = new Set([...text.matchAll(/^unit_extra\("(\w+)",[^\n]*player_controlled=True/gm)].map((m) => m[1]));
  for (const m of text.matchAll(/^unit\("(\w+)",[^\n]*/gm)) {
    const model = /model="([^"]*)"/.exec(m[0]);
    if (controlled.has(m[1]) && model && model[1] !== "") kinds.push(m[1]);
  }
}

const base = read("panels.lua");
const display = new Map([...base.matchAll(/^\s+(\w+) = \{ "([^"]+)",/gm)].map((m) => [m[1], m[2]]));
const names = [...new Set(kinds.map((k) => display.get(k) ?? k))];

const overrides = JSON.parse(read("moba_ui.json")).heroAcronyms ?? {};
const STOP = new Set(["of", "the"]);
const words = (n) => n.replace(/'/g, "").split(/[\s-]+/).filter(Boolean);
const rule = (n) => {
  const w = words(n);
  if (w.length === 1) return w[0].slice(0, 3).toUpperCase();
  let w2 = w;
  if (w.length > 3) w2 = w.filter((x) => !STOP.has(x.toLowerCase()));
  return w2.map((x) => x[0]).join("").slice(0, 3).toUpperCase();
};
const alternatives = (n) => {
  const w = words(n);
  const flat = w.join("").toUpperCase();
  const out = [];
  if (w.length > 1) out.push((w[0][0] + w[1].slice(0, 2)).toUpperCase());
  out.push(flat.slice(0, 3));
  for (let i = 1; i < flat.length; i++) for (let j = i + 1; j < flat.length; j++) out.push(flat[0] + flat[i] + flat[j]);
  return out;
};

const taken = new Map();
const result = new Map();
const collisions = [];
for (const n of names) if (overrides[n]) { result.set(n, overrides[n]); taken.set(overrides[n], n); }
for (const n of names) {
  if (result.has(n)) continue;
  let a = rule(n);
  if (taken.has(a)) {
    const first = a;
    a = alternatives(n).find((c) => !taken.has(c));
    collisions.push(`${n}: ${first} (${taken.get(first)}) -> ${a}`);
  }
  result.set(n, a);
  taken.set(a, n);
}

const lines = names.map((n) => `  ["${n}"] = "${result.get(n)}",`);
fs.writeFileSync(
  path.join(moba, "hero_acronyms.lua"),
  `-- Generated by scenarios/moba/tools/gen-hero-acronyms.mjs. Do not edit by hand.\nreturn {\n${lines.join("\n")}\n}\n`,
);
console.log(`roster ${names.length}; collisions ${collisions.length}`);
for (const c of collisions) console.log(c);
