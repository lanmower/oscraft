import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitSplit } from "./emit.mjs";
import { MIN_RISE, findCandidates, loadGrid } from "./pillar-slopes.mjs";

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const mapPath = path.join(toolDir, "..", "map.osd");
const outPath = path.join(toolDir, "..", "pillar-cells.tsv");

const grid = loadGrid(mapPath);
const candidates = findCandidates(grid);
const rows = [...candidates].sort((a, b) => a.y - b.y || a.x - b.x);

const text = [
  `# Pillar candidates from ${path.basename(mapPath)} (${grid.w}x${grid.h} grid), generated by scenarios/moba/tools/pillar-cells.mjs: every impassable slope cell with a height rise of at least ${MIN_RISE} over its open neighbours.`,
  ["x", "y", "height", "neighborHeight", "cliffBit", "blockedBit"].join("\t"),
  ...rows.map((r) => [r.x, r.y, r.height, r.neighborHeight, r.cliffBit, r.blockedBit].join("\t")),
].join("\n") + "\n";
emitSplit(path.dirname(outPath), path.basename(outPath), text, false);

console.log(`grid ${grid.w}x${grid.h}`);
console.log(`impassable slope cells: ${candidates.length}`);
console.log(`written: ${rows.length} -> ${path.basename(outPath)}`);
