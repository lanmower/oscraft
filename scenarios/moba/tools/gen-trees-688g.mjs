import fs from "node:fs";
import path from "node:path";
import { emitSplit } from "./provenance.mjs";
import { loadFootprints, readPropRecords, simCellsOf, TREE_TYPES, GX, GY } from "./pathing-688g.mjs";

const args = process.argv.slice(2);
const dir = args.includes("--dir") ? args[args.indexOf("--dir") + 1] : "scenarios/moba";
const check = args.includes("--check");
const UNIT_MILLI = 1000 / 64, TOLERANCE = 2;
const toMilli = (wx, wy) => [Math.round((GX * 64 + wx + 8192) * UNIT_MILLI), Math.round((GY * 64 + 8192 - wy) * UNIT_MILLI)];

const OFFSETS = [];
for (let dx = -TOLERANCE; dx <= TOLERANCE; dx++) for (let dy = -TOLERANCE; dy <= TOLERANCE; dy++) OFFSETS.push([dx, dy]);
OFFSETS.sort((a, b) => Math.hypot(...a) - Math.hypot(...b));

export function treeRows(dirPath) {
  const footprints = loadFootprints(path.join(dirPath, "pathing-footprints-688g.tsv"));
  const records = readPropRecords(path.join(dirPath, "props-688g.tsv"));
  const byPos = new Map();
  for (const l of fs.readFileSync(path.join(dirPath, "map.osd"), "utf8").split("\n")) {
    const m = /^prop\((\d+), "([^"]+)", (-?\d+), (-?\d+)/.exec(l);
    if (!m) continue;
    const key = `${m[3]}:${m[4]}`;
    if (!byPos.has(key)) byPos.set(key, []);
    byPos.get(key).push({ id: Number(m[1]), kind: m[2], used: false });
  }
  const turned = new Map(), rows = [];
  const unmatched = [];
  for (const d of records) {
    if (!TREE_TYPES.has(d.type)) continue;
    const cells = simCellsOf(d, footprints, turned);
    if (!cells.length) continue;
    const x0 = Math.min(...cells.map((c) => c[0])), x1 = Math.max(...cells.map((c) => c[0]));
    const y0 = Math.min(...cells.map((c) => c[1])), y1 = Math.max(...cells.map((c) => c[1]));
    if ((x1 - x0 + 1) * (y1 - y0 + 1) !== cells.length) throw new Error(`${d.type} at ${d.x},${d.y}: footprint is not a rectangle`);
    const [mx, my] = toMilli(d.x, d.y);
    let hit = null;
    for (const [dx, dy] of OFFSETS) {
      hit = (byPos.get(`${mx + dx}:${my + dy}`) || []).find((c) => !c.used) || null;
      if (hit) break;
    }
    if (hit) hit.used = true; else unmatched.push(d);
    rows.push([x0 + GX, y0 + GY, x1 - x0 + 1, y1 - y0 + 1, hit ? hit.id : -1]);
  }
  return { rows, unmatched };
}

export function treesLua(rows) {
  return [
    "-- Generated by tools/gen-trees-688g.mjs from pathing-footprints-688g.tsv, props-688g.tsv and map.osd. Do not edit by hand.",
    "-- One row per initial 6.88g tree: {cx, cy, w, h, prop} = the grid cell rectangle its footprint blocks and the map prop id that draws it (-1: none).",
    "return {",
    ...rows.map((r) => `  {${r.join(", ")}},`),
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const { rows, unmatched } = treeRows(dir);
  const next = treesLua(rows);
  const withProp = rows.filter((r) => r[4] >= 0).length;
  if (check) {
    if (emitSplit(dir, "trees_688g.lua", next, true).length) { console.error("trees_688g.lua or its provenance differs from the derived trees; run gen-trees-688g.mjs"); process.exit(1); }
    console.log(`trees in sync: ${rows.length} trees, ${withProp} with a prop`);
  } else {
    emitSplit(dir, "trees_688g.lua", next, false);
    console.log(`wrote ${rows.length} trees, ${withProp} with a prop, ${unmatched.length} without`);
  }
}
