import fs from "node:fs";
import path from "node:path";
import { emitSplit } from "./provenance.mjs";
import { fileURLToPath } from "node:url";

const moba = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, dflt) => (args.includes(name) ? args[args.indexOf(name) + 1] : dflt);
const iniPath = opt("--unit-ini", "/workspace/hy3d/output/g688-lni/unit.ini");
const DEG_PER_S_PER_TURN_RATE = 57.2958 / 0.03;

const LANE = {
  creep: ["ugho", "esen"],
  creep_ranged: ["unec", "edry"],
  creep_siege: ["umtw", "ebal"],
  creep_super: ["u001", "e00V"],
  creep_ranged_super: ["u002", "e00W"],
  creep_siege_super: ["u00R", "e026"],
  creep_mega: ["n12Q", "n12S"],
  creep_ranged_mega: ["n12R", "n12T"],
  creep_siege_mega: ["u00R", "e026"],
  courier: ["n00I"],
  courier_flying: ["e01H"],
  juggernaut_healing_ward: ["o00C"],
};

const sections = new Map();
let cur = null;
for (const line of fs.readFileSync(iniPath, "utf8").split(/\r?\n/)) {
  const head = /^\[(\w+)\]/.exec(line);
  if (head) {
    cur = { parent: head[1], turn: null };
    sections.set(head[1], cur);
    continue;
  }
  if (!cur) continue;
  const parent = /^_parent\s*=\s*"(\w+)"/.exec(line);
  if (parent) cur.parent = parent[1];
  const turn = /^turnRate\s*=\s*([\d.]+)/.exec(line);
  if (turn) cur.turn = Number(turn[1]);
}

const turnRateOf = (code) => {
  const own = sections.get(code);
  if (!own) return null;
  if (own.turn !== null) return own.turn;
  const parent = sections.get(own.parent);
  return parent && own.parent !== code ? parent.turn : null;
};
const toDegrees = (turnRate) => Math.round(turnRate * DEG_PER_S_PER_TURN_RATE);

const rows = (file) => {
  const lines = fs.readFileSync(path.join(moba, file), "utf8").split(/\r?\n/).filter((l) => l && !l.startsWith("#"));
  const header = lines[0].split("\t");
  return lines.slice(1).map((l) => Object.fromEntries(l.split("\t").map((v, i) => [header[i], v])));
};

const entries = new Map();
for (const h of rows("heroes_688g.tsv")) entries.set(h.id, toDegrees(Number(h.turn)));
for (const c of rows("creeps_688g.tsv")) {
  const rate = turnRateOf(c.src);
  if (rate !== null) entries.set(c.id, toDegrees(rate));
}
for (const [kind, codes] of Object.entries(LANE)) {
  const rate = codes.map(turnRateOf).find((r) => r !== null);
  if (rate !== undefined) entries.set(kind, toDegrees(rate));
}

const body = [...entries].sort(([a], [b]) => (a < b ? -1 : 1)).map(([kind, deg]) => `  ${kind} = ${deg},`).join("\n");
const text = `-- Generated by scenarios/moba/tools/gen-turn-rates.mjs. Do not edit by hand.
-- Kind -> degrees per second (6.88g turnRate * 57.2958 / 0.03; UNVERIFIED: the radians-per-0.03-s convention is not in the script data).
return {
${body}
}
`;
if (args.includes("--check")) {
  if (emitSplit(moba, "turn_rates.lua", text, true).length) {
    console.error("turn_rates.lua is stale: run node scenarios/moba/tools/gen-turn-rates.mjs");
    process.exit(1);
  }
} else {
  emitSplit(moba, "turn_rates.lua", text, false);
  console.log(`${entries.size} kinds -> ${path.join(moba, "turn_rates.lua")}`);
}
