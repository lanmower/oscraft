import fs from "node:fs";
import path from "node:path";

export const OWNER_GAP = "owner-gap";
const CELLS = 5;

export function parseCapabilities(text) {
  return text.split("\n").filter((line) => line.startsWith("| CAP-")).map((line) => {
    const cells = line.split("|").slice(1, -1).map((cell) => cell.trim());
    return { id: cells[0], capability: cells[1], status: cells[2], provider: cells[3], gate: cells[4], cellCount: cells.length };
  });
}

export function planRows(rows, targets) {
  const errors = [];
  const plan = [];
  const seen = new Set();
  for (const row of rows) {
    if (row.cellCount !== CELLS) {
      errors.push(`${row.id} has ${row.cellCount} cells, expected ${CELLS}`);
      continue;
    }
    if (seen.has(row.id)) errors.push(`duplicate capability id ${row.id}`);
    seen.add(row.id);
    const prefix = row.id.split("-")[1];
    const entry = targets.overrides[row.id] ?? targets.categories[prefix];
    if (!entry) {
      errors.push(`${row.id} has no Bevy target`);
      continue;
    }
    if (entry.stage !== OWNER_GAP && !targets.stages[entry.stage]) {
      errors.push(`${row.id} names unknown stage ${entry.stage}`);
      continue;
    }
    plan.push({ ...row, target: entry.target, stage: entry.stage });
  }
  return { plan, errors };
}

export function gameErrors(games, root) {
  return games.filter((game) => !fs.existsSync(path.join(root, "scenarios", game.scenario))).map((game) => `game ${game.scenario} has no scenarios/${game.scenario} directory`);
}

export function renderDoc(plan, targets) {
  const count = (stage) => plan.filter((row) => row.stage === stage).length;
  const lines = [
    "# Oscraft on Bevy: capability parity",
    "",
    "Generated by `node scripts/check-bevy-parity.mjs --write` from `docs/CAPABILITIES.md` and `scripts/bevy-parity/targets.json`. Do not edit this file by hand: the check fails on any drift.",
    "",
    "Plan: `specs/oscraft-on-bevy.md`. Stage S0 is this file: every capability row has a Bevy target, and S1 to S6 carry them.",
    "",
    "## Stages",
    "",
    "| stage | meaning | rows |",
    "|---|---|---|",
    ...Object.entries(targets.stages).map(([stage, meaning]) => `| ${stage} | ${meaning} | ${count(stage)} |`),
    `| ${OWNER_GAP} | decided by the owner; no stage yet | ${count(OWNER_GAP)} |`,
    "",
    "## Capability rows",
    "",
    "| id | capability | oscraft status | Bevy target | stage | Bevy status |",
    "|---|---|---|---|---|---|",
    ...plan.map((row) => `| ${row.id} | ${row.capability} | ${row.status} | ${row.target} | ${row.stage} | ${row.stage === OWNER_GAP ? "owner-held" : "planned"} |`),
    "",
    "## Games",
    "",
    "| scenario | Bevy target | stage |",
    "|---|---|---|",
    ...targets.games.map((game) => `| ${game.scenario} | ${game.target} | ${game.stage} |`),
    "",
    "## Decisions and reasons",
    "",
    ...targets.decisions.map((decision) => `- ${decision.id}: ${decision.decision} Reason: ${decision.reason}`),
    "",
  ];
  return lines.join("\n");
}
