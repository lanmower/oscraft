import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED = [
  "ability_fx.lua", "ability_keys.lua", "buff_fx.lua", "hero_acronyms.lua", "hero_sides.lua",
  "shops_688g.lua", "trees_688g.lua", "turn_rates.lua", "ui_fill.lua",
];
const EXTERNAL = new Set(["ability_text_688g.lua"]);
for (const name of GENERATED) {
  const head = readFileSync(resolve(root, "scenarios/moba", name), "utf8").split("\n")[0];
  if (!head.startsWith("-- Generated by") || !head.includes("Do not edit by hand")) throw new Error(name + " has no generator banner");
}
const runner = readFileSync(resolve(root, "scripts/check-all.mjs"), "utf8");
const generatorGates = [...runner.matchAll(/"(gen-|apply-)[^"]+\.mjs"/g)].length;
if (generatorGates < 12) throw new Error("check-all.mjs lost the generator --check gates");
console.log("generated lua ok " + GENERATED.length + " banners, " + generatorGates + " generator gates, external=" + [...EXTERNAL].join());
