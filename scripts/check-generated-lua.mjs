import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const moba = resolve(root, "scenarios/moba");
const GENERATED = [
  "ability_fx.lua", "ability_keys.lua", "buff_fx.lua", "hero_acronyms.lua", "hero_sides.lua",
  "shops_688g.lua", "trees_688g.lua", "turn_rates.lua", "ui_fill.lua",
];
for (const name of GENERATED) {
  const head = readFileSync(join(moba, name), "utf8").split("\n")[0];
  if (!head.startsWith("-- Generated by") || !head.includes("Do not edit by hand")) throw new Error(name + " has no generator banner");
}
const runner = readFileSync(resolve(root, "scripts/check-all.mjs"), "utf8");
const generatorGates = runner.split("\n").filter((line) => line.includes("gen-") || line.includes("apply-")).length;
if (generatorGates < 12) throw new Error("check-all.mjs lost the generator gates");
const tmp = mkdtempSync(join(tmpdir(), "generated-lua-check-"));
try {
  for (const f of readdirSync(moba)) {
    if (f.endsWith(".tsv") || f.endsWith(".osd")) copyFileSync(join(moba, f), join(tmp, f));
  }
  const real = readFileSync(join(moba, "ability_fx.lua"), "utf8");
  writeFileSync(join(tmp, "ability_fx.lua"), real.replace("dur = ", "dur = 999999 "));
  let refused = false;
  try {
    execFileSync(process.execPath, [resolve(root, "scenarios/moba/tools/gen-ability-fx.mjs"), "--out", tmp, "--check"], { encoding: "utf8" });
  } catch { refused = true; }
  if (!refused) throw new Error("a mutated generated output did not fail the generator --check gate");
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
console.log("generated lua ok " + GENERATED.length + " banners, " + generatorGates + " gates, mutation case caught");
