// Generates docs/REFERENCE.md from the .osd text of a scenario.
// Usage: node scripts/gen-reference.mjs [scenario-dir] [out-file]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.argv[2] ?? join(root, "scenarios/moba");
const out = process.argv[3] ?? join(root, "docs/REFERENCE.md");

function splitTop(s) {
  const parts = [];
  let depth = 0, quote = null, cur = "";
  for (const ch of s) {
    if (quote) { cur += ch; if (ch === quote) quote = null; continue; }
    if (ch === '"') { quote = ch; cur += ch; continue; }
    if ("([{".includes(ch)) depth++;
    if (")]}".includes(ch)) depth--;
    if (ch === "," && depth === 0) { parts.push(cur.trim()); cur = ""; continue; }
    cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

function parseCall(line) {
  const m = line.match(/^(\w+)\((.*)\)\s*(#.*)?$/);
  if (!m) return null;
  const pos = [], kw = {};
  for (const a of splitTop(m[2])) {
    const k = a.match(/^(\w+)=(.*)$/s);
    if (k) kw[k[1]] = k[2]; else pos.push(a);
  }
  return { fn: m[1], pos, kw, trail: m[3] ?? "" };
}

const unq = (s) => (s ?? "").replace(/^"|"$/g, "");
const sourced = (text) => /SteamDatabase|source/i.test(text) && !/^#?\s*UNVERIFIED\s*$/.test(text);

const calls = [];
for (const f of readdirSync(dir).filter((n) => n.endsWith(".osd")).sort()) {
  let comments = [];
  for (const raw of readFileSync(join(dir, f), "utf8").split("\n")) {
    const line = raw.trim();
    if (line.startsWith("#")) { comments.push(line); continue; }
    if (!line) { continue; }
    const c = parseCall(line);
    if (c) { c.file = f; c.note = (comments.at(-1) ?? "") + " " + c.trail; calls.push(c); }
    comments = [];
  }
}
const by = (fn) => calls.filter((c) => c.fn === fn);
const flag = (c) => ((c.note.includes("SteamDatabase") || c.note.includes("same source file")) && !/^\s*# \w+: UNVERIFIED/.test(c.note) ? "partly sourced" : "UNVERIFIED");

const effects = (s) =>
  [...s.matchAll(/effect\("(\w+)"((?:,\s*\w+=-?\d+)*)\)/g)]
    .map((m) => `${m[1]}${m[2].replace(/,\s*/g, " ").trim() ? " (" + m[2].replace(/^,\s*/, "").replace(/,\s*/g, ", ") + ")" : ""}`)
    .join("; ");

const channels = Object.fromEntries(by("channel").map((c) => [unq(c.pos[0]), c.pos[1]]));
const skills = Object.fromEntries(by("skill").map((c) => [unq(c.pos[0]), c.kw]));
const extras = Object.fromEntries(by("unit_extra").map((c) => [unq(c.pos[0]), c.kw]));
const abilityNames = by("ability").map((c) => unq(c.pos[0]));
const unitNames = by("unit").map((c) => unq(c.pos[0]));
const itemActive = new Set(by("item").map((c) => unq(c.kw.ability)));

const L = [];
L.push("# Reference", "", "Generated by `node scripts/gen-reference.mjs` from `scenarios/moba/*.osd`. Do not edit by hand.", "",
  "Each row is marked `partly sourced` when its `.osd` comment cites a data source for some fields (the comment names which; speed, radius, range and sight stay placeholders) and `UNVERIFIED` otherwise. Ticks run at 16 per second. Distances are milli-units (1000 = one map cell).", "");

const heroes = by("unit").filter((c) => c.kw.abilities && extras[unq(c.pos[0])]?.player_controlled === "True");
L.push(`## Heroes (${heroes.length})`, "",
  "| Hero | Health | Speed | Radius | Damage | Range | Period | Armor | Abilities | Status |", "|---|---|---|---|---|---|---|---|---|---|");
for (const c of heroes)
  L.push(`| ${unq(c.pos[0])} | ${c.pos[1]} | ${c.pos[2]} | ${c.pos[3]} | ${c.kw.weapon_damage} | ${c.kw.weapon_range_milli} | ${c.kw.weapon_period} | ${c.kw.armor ?? 0} | ${JSON.parse(c.kw.abilities).join(", ")} | ${flag(c)} |`);

const heroAbilities = new Set(heroes.flatMap((c) => JSON.parse(c.kw.abilities)));
L.push("", `## Abilities (${abilityNames.length})`, "",
  "| Ability | Cooldown | Cost | Target | Effects | Channel | Notes | Status |", "|---|---|---|---|---|---|---|---|");
for (const c of by("ability")) {
  const n = unq(c.pos[0]);
  const notes = [];
  if (c.kw.projectile_speed_milli) notes.push(`projectile ${c.kw.projectile_speed_milli}`);
  if (c.pos[1] === "100000") notes.push("passive, cast once at spawn");
  if (itemActive.has(n)) notes.push("item active");
  if (heroAbilities.has(n) && skills[n]) notes.push(skills[n].ultimate === "True" ? "ultimate" : "skill");
  L.push(`| ${n} | ${c.pos[1]} | ${c.pos[2]} | ${unq(c.pos[3])} | ${effects(c.pos[4])} | ${channels[n] ?? ""} | ${notes.join(", ")} | ${flag(c)} |`);
}

L.push("", `## Skill ranks (${Object.keys(skills).length})`, "",
  "Ranks per ability. Gates are the character level needed for each rank.", "",
  "| Ability | Ultimate | Gates | Damage | Cooldown | Energy |", "|---|---|---|---|---|---|");
for (const [n, k] of Object.entries(skills))
  L.push(`| ${n} | ${k.ultimate === "True" ? "yes" : "no"} | ${k.gates} | ${k.damage} | ${k.cooldown} | ${k.energy} |`);

const itemFlags = (c) => ["consumable", "no_buy", "no_sell", "enhancement"].filter((k) => c.kw[k] === "True").join(", ");
L.push("", `## Items (${by("item").length})`, "",
  "Generated from Valve's items.txt by scripts/gen-items.mjs; stats are listed by name (armor, regeneration in hundredths).", "",
  "| Item | Cost | Stats | Active | Recipe | Shops | Tier | Charges | Stock | Flags |", "|---|---|---|---|---|---|---|---|---|---|");
for (const c of by("item")) {
  const stats = c.kw.stats ? Object.entries(JSON.parse(c.kw.stats)).map(([k, v]) => `${k} ${v}`).join(", ") : "";
  const shops = c.kw.shops ? JSON.parse(c.kw.shops).join("/") : "";
  const stock = c.kw.stock_max ? `${c.kw.stock_initial}/${c.kw.stock_max} per ${c.kw.stock_time_s} s` : "";
  L.push(`| ${unq(c.pos[0])} | ${c.pos[1]} | ${stats} | ${unq(c.kw.ability)} | ${c.kw.components ? JSON.parse(c.kw.components).join(" + ") : ""} | ${shops} | ${c.kw.neutral_tier ?? ""} | ${c.kw.charges ?? ""} | ${stock} | ${itemFlags(c)} |`);
}

L.push("", `## Units (${unitNames.length})`, "",
  "| Unit | Health | Speed | Radius | Damage | Range | Period | Armor | Deny % | Bounty | XP | Status |", "|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const c of by("unit")) {
  const n = unq(c.pos[0]), e = extras[n] ?? {};
  L.push(`| ${n} | ${c.pos[1]} | ${c.pos[2]} | ${c.pos[3]} | ${c.kw.weapon_damage ?? ""} | ${c.kw.weapon_range_milli ?? ""} | ${c.kw.weapon_period ?? ""} | ${c.kw.armor ?? ""} | ${c.kw.deny_pct ?? ""} | ${e.bounty ?? ""} | ${e.xp_bounty ?? ""} | ${flag(c)} |`);
}

L.push("", "## Behaviours", "", "| Name | Trigger | Action | Ability |", "|---|---|---|---|");
for (const c of by("behaviour"))
  L.push(`| ${unq(c.pos[0])} | ${unq(c.kw.trigger)} | ${unq(c.kw.action)} | ${unq(c.kw.ability ?? c.kw.tag)} |`);

const rules = readFileSync(join(dir, "hero_rules.txt"), "utf8").split("\n").filter((l) => /^\w+=/.test(l));
L.push("", "## Hero rules", "", "From `hero_rules.txt`. All UNVERIFIED placeholders.", "", "| Key | Value |", "|---|---|");
for (const r of rules) { const [k, v] = r.split("="); L.push(`| ${k} | ${v} |`); }

const spawns = by("spawn"), neutral = spawns.filter((c) => c.pos[1] === "-1");
L.push("", "## Neutral spawns", "", "| Unit | Count |", "|---|---|");
const cnt = {};
for (const c of neutral) cnt[unq(c.pos[0])] = (cnt[unq(c.pos[0])] ?? 0) + 1;
for (const [k, v] of Object.entries(cnt)) L.push(`| ${k} | ${v} |`);

writeFileSync(out, L.join("\n") + "\n");
console.log(`wrote ${out}: heroes=${heroes.length} abilities=${abilityNames.length} items=${by("item").length} units=${unitNames.length}`);
