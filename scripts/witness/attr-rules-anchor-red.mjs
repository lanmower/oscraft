import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const checker = path.join(root, "scripts", "check-attr-rules-anchors.mjs");
const config = path.join(root, "scripts", "mod-host", "splice-anchors.json");
const scratch = path.join(root, "..", "tmp", "oscraft", "anchors");
const packs = ["moba", "moba-acronyms", "bota", "duel-routes"];
const generators = ["scenarios/moba/tools/gen-heroes.mjs", "scenarios/bota/tools/gen-heroes.mjs"];

const copyRoot = (name, mutate) => {
  const dir = path.join(scratch, name);
  fs.rmSync(dir, { recursive: true, force: true });
  const files = Object.fromEntries([
    ...packs.map((pack) => [`scenarios/${pack}/attr_rules.txt`, fs.readFileSync(path.join(root, "scenarios", pack, "attr_rules.txt"), "utf8")]),
    ...generators.map((gen) => [gen, fs.readFileSync(path.join(root, gen), "utf8")]),
  ]);
  mutate?.(files);
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), text);
  }
  return dir;
};
const run = (dir) => spawnSync(process.execPath, [checker, `--root=${dir}`, `--config=${config}`], { encoding: "utf8" });

const failures = [];
const expect = (name, ok) => {
  console.log(`${ok ? "ok" : "FAIL"} ${name}`);
  if (!ok) failures.push(name);
};

let result = run(copyRoot("real"));
expect("the real packs pass with one BEGIN and one END each", result.status === 0 && result.stdout.includes("attr_rules anchors ok"));

result = run(copyRoot("missing-end", (files) => {
  const key = "scenarios/moba/attr_rules.txt";
  files[key] = files[key].split("\n").filter((line) => !line.startsWith("# END generated by scenarios/moba/tools/gen-heroes.mjs")).join("\n");
}));
expect("a missing END anchor fails and names the pack", result.status === 1 && result.stderr.includes("moba: 0 END anchors"));

result = run(copyRoot("duplicate-begin", (files) => {
  const key = "scenarios/moba/attr_rules.txt";
  const begin = files[key].split("\n").find((line) => line.startsWith("# BEGIN generated by scenarios/moba/tools/gen-heroes.mjs"));
  files[key] = files[key] + "\n" + begin + "\n";
}));
expect("a duplicate BEGIN anchor fails and names the pack", result.status === 1 && result.stderr.includes("moba: 2 BEGIN anchors"));

result = run(copyRoot("end-before-begin", (files) => {
  const key = "scenarios/moba-acronyms/attr_rules.txt";
  const lines = files[key].split("\n");
  const b = lines.findIndex((line) => line.startsWith("# BEGIN generated"));
  const e = lines.findIndex((line) => line.startsWith("# END generated"));
  [lines[b], lines[e]] = [lines[e], lines[b]];
  files[key] = lines.join("\n");
}));
expect("an END before its BEGIN fails and names the pack", result.status === 1 && result.stderr.includes("moba-acronyms: END before BEGIN"));

result = run(copyRoot("stray", (files) => {
  files["scenarios/duel-routes/attr_rules.txt"] += "\n# END generated by scenarios/moba/tools/gen-heroes.mjs\n";
}));
expect("a stray anchor in an unmanaged pack fails and names the pack", result.status === 1 && result.stderr.includes("duel-routes: stray generator anchor"));

result = run(copyRoot("generator-drift", (files) => {
  files["scenarios/bota/tools/gen-heroes.mjs"] = files["scenarios/bota/tools/gen-heroes.mjs"].split("# END generated by").join("# END moved by");
}));
expect("a generator that stops writing the END anchor fails and names it", result.status === 1 && result.stderr.includes("scenarios/bota/tools/gen-heroes.mjs does not write the END anchor"));

if (failures.length) {
  console.error(`attr_rules anchor red tests failed: ${failures.join("; ")}`);
  process.exit(1);
}
console.log("attr_rules anchor red tests ok (6 cases)");
