import fs from "node:fs";
import path from "node:path";
const [dir, out] = process.argv.slice(2);
const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"));
const byRel = new Map(Object.entries(manifest.modules ?? {}).map(([stem, rel]) => [rel, stem]));
const SKIP_DIRS = new Set(["bundle", "tools", "fixtures", "assets"]);
const files = [];
const walk = (base, rel) => {
  for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
    const next = rel ? rel + "/" + entry.name : entry.name;
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(path.join(base, entry.name), next);
    } else if (entry.name.endsWith(".lua")) files.push([next, byRel.get(next) ?? path.basename(entry.name, ".lua")]);
  }
};
walk(dir, "");
files.sort((a, b) => a[1].localeCompare(b[1]));
let text = "-- generated by scripts/bundle-lua.mjs: one package.preload entry per module\n";
for (const [rel, stem] of files) {
  text += "package.preload[" + JSON.stringify(stem) + "] = function(...)\n" + fs.readFileSync(path.join(dir, rel), "utf8") + "\nend\n";
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, text);
console.log("bundled " + files.length + " lua modules into " + out);
