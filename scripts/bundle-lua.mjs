import fs from "node:fs";
import path from "node:path";
const [dir, out] = process.argv.slice(2);
const names = fs.readdirSync(dir).filter((f) => f.endsWith(".lua")).sort();
let text = "-- generated by scripts/bundle-lua.mjs: one package.preload entry per module\n";
for (const f of names) {
  const name = f.slice(0, -4);
  text += "package.preload[" + JSON.stringify(name) + "] = function(...)\n" + fs.readFileSync(path.join(dir, f), "utf8") + "\nend\n";
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, text);
console.log("bundled " + names.length + " lua modules into " + out);
